#!/bin/bash

# =====================================================
# СБОРОЧНЫЙ КОНВЕЙЕР ДЛЯ JAVA-LIBRARY-APP
# =====================================================

set -e  # Остановить выполнение при первой ошибке

# Цвета для красивого вывода
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m' # Без цвета

echo -e "${GREEN}========================================${NC}"
echo -e "${GREEN}  ЗАПУСК СБОРОЧНОГО КОНВЕЙЕРА${NC}"
echo -e "${GREEN}========================================${NC}"

# Получаем текущую ветку Git
BRANCH=$(git rev-parse --abbrev-ref HEAD)
echo -e "${YELLOW}Текущая ветка: ${BRANCH}${NC}"

# Папка для публикации артефактов
PUBLISH_DIR="./publish"

# =====================================================
# ШАГ 1: Получение исходного кода из Git
# =====================================================
echo -e "\n${GREEN}[ШАГ 1] Получение исходного кода из Git...${NC}"
git status > /dev/null
echo -e "${GREEN}✓ Код получен успешно${NC}"

# =====================================================
# ШАГ 2: Компиляция кода программы и тестов
# =====================================================
echo -e "\n${GREEN}[ШАГ 2] Компиляция кода и тестов...${NC}"
mvn clean test-compile -q
echo -e "${GREEN}✓ Компиляция прошла успешно${NC}"

# =====================================================
# ШАГ 3: Запуск тестов (ТОЛЬКО для веток feature/XXX)
# =====================================================
if [[ "$BRANCH" == feature/* ]]; then
    echo -e "\n${GREEN}[ШАГ 3] Запуск тестов (ветка feature)...${NC}"
    mvn test -q
    echo -e "${GREEN}✓ Все тесты прошли успешно${NC}"
else
    echo -e "\n${YELLOW}[ШАГ 3] Пропуск тестов (ветка не feature/...)${NC}"
fi

# =====================================================
# ШАГ 4: Статический анализатор Checkstyle (ТОЛЬКО для ветки develop)
# =====================================================
if [[ "$BRANCH" == "develop" ]]; then
    echo -e "\n${GREEN}[ШАГ 4] Запуск Checkstyle (статический анализ)...${NC}"
    mvn checkstyle:check -q
    echo -e "${GREEN}✓ Checkstyle прошел успешно${NC}"
else
    echo -e "\n${YELLOW}[ШАГ 4] Пропуск Checkstyle (ветка не develop)${NC}"
fi

# =====================================================
# ШАГ 5: Измерение тестового покрытия JaCoCo
# =====================================================
echo -e "\n${GREEN}[ШАГ 5] Измерение тестового покрытия (JaCoCo)...${NC}"
mvn jacoco:prepare-agent test jacoco:report -q
echo -e "${GREEN}✓ Отчет о покрытии сгенерирован: target/site/jacoco/index.html${NC}"

# =====================================================
# ШАГ 6: Установка артефактов в локальный репозиторий (только при успехе)
# =====================================================
echo -e "\n${GREEN}[ШАГ 6] Установка артефакта в локальный репозиторий...${NC}"
mvn install -DskipTests -q
echo -e "${GREEN}✓ Артефакт установлен в ~/.m2/repository/${NC}"

# =====================================================
# ШАГ 7: Проверка критериев выпуска (покрытие >= 50%)
# =====================================================
echo -e "\n${GREEN}[ШАГ 7] Проверка критериев выпуска (покрытие >= 50%)...${NC}"
# Запускаем фазу verify, которая выполнит jacoco:check с настройками из pom.xml
mvn verify -q
echo -e "${GREEN}✓ Критерии выпуска выполнены${NC}"

# =====================================================
# ШАГ 8: Публикация артефакта в заданную папку
# =====================================================
echo -e "\n${GREEN}[ШАГ 8] Публикация артефакта...${NC}"
mkdir -p "$PUBLISH_DIR"
cp target/java-library-app-1.0.jar "$PUBLISH_DIR/"
echo -e "${GREEN}✓ Артефакт опубликован в папку: ${PUBLISH_DIR}/${NC}"

# =====================================================
# ФИНАЛ
# =====================================================
echo -e "\n${GREEN}========================================${NC}"
echo -e "${GREEN}  КОНВЕЙЕР ЗАВЕРШЕН УСПЕШНО!${NC}"
echo -e "${GREEN}========================================${NC}"
echo -e "Артефакт: ${PUBLISH_DIR}/java-library-app-1.0.jar"
echo -e "Отчет покрытия: target/site/jacoco/index.html"